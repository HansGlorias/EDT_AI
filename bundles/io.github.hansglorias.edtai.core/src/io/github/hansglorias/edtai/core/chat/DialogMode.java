package io.github.hansglorias.edtai.core.chat;

/**
 * Режим вопроса: в каком виде нужен ответ. Модель и формат истории не
 * меняются — к вопросу прикладывается короткая инструкция.
 */
public enum DialogMode {

    ANSWER("Ответ", "Дай прямой ответ на вопрос — коротко и по делу. Важные оговорки — в конце, одной-двумя строками."),
    OPTIONS("Варианты", "Предложи 2–4 варианта решения. Для каждого: суть, плюсы, минусы и когда его выбирать. Код — только"
            + " если без него не понять, коротко. Не выбирай за меня и ничего не меняй в проекте."),
    RECOMMEND("Рекомендация", "Сравни возможные варианты, выбери один и обоснуй: почему он, чем хуже остальные, какие риски"
            + " и как их снять. В конце — первый шаг."),
    PLAN("План", "Составь план реализации: цель, допущения, шаги по порядку (какие объекты, модули и процедуры менять),"
            + " риски, как проверить результат. Изучать проект инструментами можно, но план не выполняй и файлы не меняй.");

    private final String label;
    private final String instruction;

    DialogMode(String label, String instruction) {
        this.label = label;
        this.instruction = instruction;
    }

    /** Название для кнопки и ленты: «План». */
    public String label() {
        return label;
    }

    /** Что дописывается модели к вопросу. */
    public String instruction() {
        return instruction;
    }

    /** Вложение к вопросу: в ленте — «режим «План»», модели — инструкция. */
    public Attachment attachment() {
        return Attachment.mode(label, instruction);
    }
}
